<p>Un disco de  hierro para cocinar, arrumbado en el fondo de una alacena bajo una escalera no  suele ser una de las sorpresas habituales que deparan lugares como Mar Azul, en  la costa atlántica argentina. Sin embargo, si uno acepta la invitación de la  familia Mantiñán (a quienes en confianza llamamos Los Mantos), no sólo es  posible que suceda: sucede. Después de haber sido curado por enésima vez con  brasas al rojo vivo, el disco quedó listo para ser usado. El asunto era con  qué. Bastó apenas una tarde de playa, a puro sol y con olas marinas que  ayudaron al juego y el disfrute para que la receta saliera a la superficie,  apenas caída la esperanza de asar pescado fresco en la parrilla de la casa,  sobre la calle Copacabana. <u></u></p>

