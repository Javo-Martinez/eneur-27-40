<p>  ¿Qué clase de  receta, podrá preguntarse el lector, es aquella que no indica cantidades?  Sucede que, como lo indica el título, el componente <em>sui generis</em> estuvo en la improvisación, una <em>jam sesión</em> culinaria en la que los ingredientes bailaron al ritmo  del ojo que calibra. Sin secretos, calentamos el disco con fuego fuerte hecho  con leña, agregamos aceite generosamente y antes de que entrara en hervor,  agregamos cebollas y ajíes cortados en tiras de importante tamaño, luego el  pollo y el cerdo cortado en cubos, hasta que la carne quedó sellada. Luego  fuimos incorporando los ingredientes de acuerdo a su dureza, hirviéndolos en  sus propios jugos. Para los últimos cinco minutos de cocción quedaron los  champiñones. El resultado fueron generosas porciones recibidas con alegría por  los comensales y oportunamente regadas de vinos y cervezas.  O de cómo experimentar con lo conocido y  sentir el sabor de lo nuevo. ¡Bon appétit!</p>
