<p>Al otro lado de la cordillera, el 15 de abril de 1988,  Gabriel Parra, mítico baterista del grupo chileno <strong>Los Jaivas</strong> se mató en un  accidente automovilístico en un lugar conocido como <em>La curva del Diablo</em>. Como homenaje, sus compañeros de banda  publicaron el LP <em>Si tú no estás</em>, para  el cual el difunto músico había grabado las baterías de los temas que abren y  cierran el álbum y la letra de otros tres que se incluirían en el disco. Con  letra del Gato Alquinta, <em>Pájaro errante</em> se convirtió en una de las obras cumbres de la banda.<br />
