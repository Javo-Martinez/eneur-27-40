<p>Si el hilo conductor de estas reseñas breves es el tema del  número ENEUR en cuestión, convengamos que El Pajarito puede tener cientos, por  no decir miles, de ramificaciones y tratamientos posibles. Afín a nuestra  trayectoria de menefreguismo, hemos decidido hacer la selección en base a la  diversidad tan mentada en los últimos años. Como todo pájaro merece volar  libremente, se nos ocurrió que no había mejor excusa que esa para dejar volar  nuestra imaginación, la misma de la que parecemos carecer en la frase que  antecede a este punto y aparte.</p>

