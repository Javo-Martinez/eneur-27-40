<p>  <strong>Charlie <em>Bird </em>Parker</strong>,  el legendario saxofonista, grabó Ornithology, un single editado en 1946,  haciendo referencia a su ornitológico apodo. Compuesto en colaboración con  Benny Harris y construido sobre un estándar del género que se convirtió, a su  vez, en uno de ellos; un <em>contrafact</em>,  una nueva melodía resultante de la reescritura de una conocida estructura  armónica. Versionado una y otra vez por cantantes de <em>scat</em>, es una muestra cabal de lo que la cabeza y los dedos de  Parker eran capaces de hacer.  </p>
