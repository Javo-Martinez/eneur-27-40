<p>Versionada en infinidad de ocasiones, entre tantos otros por  Johnny Cash, Joe Bonamassa, Kiko Veneno, K. D. lang y Joe Cocker, <em>Bird on a wire</em> es una composición  melancólica sobre el camino hacia ser libre, como el borracho en el coro de  medianoche, la lombriz en el anzuelo, un caballero de algún viejo libro o el  mentado pajarito sobre el cable. Grabada en 1968, fue el puntapié inicial de  los recitales de <strong>Leonard Cohen</strong> quien se anotició del tremendo parecido en sus  patrones líricos con la canción de otro autor de Nashville gracias al amigo  Kris Kristofferson. </p>

