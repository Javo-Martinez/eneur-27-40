<p>Me alejé a rastras del arbusto que crecía junto a la ventana  y eché a correr. La huida era lo único que me daba seguridad.
  Si paraba, me pondría a aullar. Sabía que no tenía
  que parar. Llevaba aquello en las tripas. En mi garganta seca 
  cerrada. Encorvado dolorido acobardado herido de muerte
  aullaría en la noche. Aterrando aquellas casas. Aquel césped
  bien cuidado. Aquellos pianos suavemente lustrados. Temblarían
  las salas. Se encogerían las alfombras. Si paraba.
  Si en algún momento lo dejaba salir. Aquel animal herido
  apaleado. Y no lo hice. No aullé. Seguí corriendo. Aún tenía
  puestas las zapatillas. Y no aullé.<br />
  <br />
  El club estaba cerrado. Manejé hasta casa. El interior
  estaba oscuro. No paraba de decirme: estás acabado. Has
  llegado al fin. Quería quedarme quieto en un espacio vacío
  y juntar las manos de un golpe. Quería arrastrarme. Quería
  cavar un túnel. Caminar parecía poco natural. Quizá si hubiera
  andado en cuatro patas no habría sido tan doloroso.</p>
