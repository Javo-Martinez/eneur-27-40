<p>Tropecé en colores terrosos que guardaban tus cabellos crespos. Desperté pensándote cuando  un lucero perdido me encontró en la amazonía extraña de la tierra. Tierra que con tus propias manos<br />
  plantaste de verde utopía. Tus pies nacieron al ritmo de los calores y florecieron amplios sobre 
  pañuelos. Aunque vos caminaste descalza siempre, armando en cada paso el comercio de dioses y 
  mortales.</p>
<p>  Madre-sin-nombre, que me has criado en cuentos fenicios, a dos aguas hendidas con eso que  hay de árabe en tus peleas. Que me enseñaste a callar cuando la lluvia habla y a obedecer el despiste  del tiempo. Madre-muchos-nombres, que una noche confesaste ser vieja y aún celebrar el amor como pequeña.<br />
  <br />
  Perlita, como me llamabas, crecí de belleza en belleza gracias a tu mirada de oro profundo. 
  ¡Cómo me habría gustado tocar tu útero de música y nacer de alma morena! Pero heredé, milagro, tus
  ojos verdes y el cuerpo que late inmediato y te busca, mientras vos danzás lejana, sobre aguas 
  tremebundas y llamas austeras, rescatando tu sangre de imperio y mareas.<br />
  <br />
  Escucho el sabor de los tambores, que son tus pies en el desierto. Cada noche tu estrella me
  cuenta de pasados faraones que rumeaban tu historia perdida, y pienso en las muchas madres que he
  tenido y que fluyen en vos, diosa&ndash;cultivo.<br />
  <br />
  Tropiezo hoy con tu mirada.<br />
  <br />
  Suave enseñanza de poesía.<br />
  <br />
  Madre África mía.</p>
