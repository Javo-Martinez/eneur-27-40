<p>La colaboración entre la imagen y la poesía  tiene la particularidad de generar un efecto novedoso. No necesariamente porque las aventuras que emprende sea el descubrimiento de un formato, sino porque en cada encuentro, ese dúo tienen una particular y única forma de ser.  En ese sentido, los poemas de Cintia Zaremsky y las fotos de Uri Gordon se articulan de un modo que no sólo se proponen como una novedad sino que va más allá de las precedencias de una producción sobre otra y de los mecanismos creativos que ha dado como resultado un libro de una cuidadísima edición; un objeto de calidad acorde a su contenido.</p>
<p>Es interesante pensar esta aventura editorial a partir de su título que esconde un par de hilos para pensar el total del conjunto: la fotografía como impresión derivada de la luz y sus efectos; los poemas derivados del recorte fotográfico; la referencia al concepto náutico del desvío; desplazamiento del lector por sobre la superficie de la relación ente el color, la forma, las letras; el deambular en la ciudad, donde se han producido las imágenes y las palabras que son los ladrillos con los que se construyó este estupendo libro.</p>

