	<strong>Grete Stern. Los sueños 1948 – 1951</strong><br />
	MALBA - Museo de Arte Latinoamericano de Buenos Aires
    <br />
    En pleno apogeo peronista, durante los años 1948 y 1951, la fotógrafa alemana, por entonces ya radicada en Buenos Aires, realizó una serie de 46 fotomontajes para la sección <em>El psicoanálisis le ayudará</em>, de la revista Idilio. En ella, sus obras acompañaban las interpretaciones que su director, bajo seudónimo, hacía de los sueños que las propias lectoras enviaban. Un curioso proyecto que tuvo como resultado unas inquietantes imágenes oníricas.
