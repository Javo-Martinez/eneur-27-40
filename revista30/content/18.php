    <strong>Junio</strong>
    <br />
	<strong>John Lennon: sus años en Nueva York (1971-1980)</strong><br />
	Centro Cultural Recoleta
    <br />
    El estadounidense Bob Gruen tuvo el doble privilegio de ser amigo y fotógrafo personal de John Lennon.  Sus registros de la familia Lennon-Ono comenzaron en 1971, con el desembarco en Nueva York del músico inglés, después de la ruptura con The Beatles. Gruen condensó semejante experiencia en fotos de Lennon en los que lo muestra en grabaciones, en plena vida familiar y en la intimidad de su cotidiano; un trabajo que da testimonio de uno de los artistas más importantes que ha dado este mundo.
 </p>
