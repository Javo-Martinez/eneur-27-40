<p style="
    margin-left: 190px;
    margin-top: 550px;
">Esa mujer se parecía a la palabra nunca,<br />
desde la nuca le subía un encanto particular<br />
una especie de olvido donde guardar los ojos,<br />
esa mujer se me instalaba en el costado  izquierdo.</p>
<p style="
    margin-left: 190px;
">Atención atención yo gritaba atención<br />
  pero ella invadía como el amor, como la noche,<br />
  las últimas señales que hice para el otoño<br />
  se acostaron tranquilas bajo el oleaje de sus  manos.</p>
<p style="
    margin-left: 190px;
">Dentro de mí estallaron ruidos secos,<br />
  caían a pedazos la furia, la tristeza,<br />
  la señora llovía dulcemente<br />
  sobre mis huesos parados en la soledad.</p>
<p style="
    margin-left: 190px; width: 500px;
">Cuando se fue yo tiritaba como un condenado,<br />
  con un cuchillo brusco me maté,<br />
  voy a pasar toda la muerte tendido con su nombre,<br />
  él moverá mi boca por la última vez.</p>
<p style="
    margin-left: 190px;
"><strong>Gotán</strong><br />
  Juan Gelman<br />
1930-2014</p>
