<p>Quizá para muchos 2013 haya sido el año en el que vivimos inciertamente,  porque como si de una trenza de palabras se tratara, los que sobrevivimos lo  hicimos confirmando la sólida tozudez de la incertidumbre. Quizá para muchos  otros 2013 haya sido un año más, o un año menos, o un año poderosamente  ascendente. Sea como fuere, todos hemos sido <em>clientes</em> de una montaña de música que no siempre nos dejó escuchar el  horizonte. En esta recopilación no están todos los que son, y ni siquiera los  que son acaban de estar en el top. Es, simplemente, un recorrido  videográfico-musical que nos ayudará a recordar (u olvidar) todo lo  malditamente lindo que acaba de pasarnos.</p>
