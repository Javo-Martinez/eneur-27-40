<p>Y como el sur también existe, cerramos este compilado haciéndole un ole a tanta anglofilia. En su cuarto disco, Omar Giammarco se desata de algunas de las riendas que embridaban sus trabajos anteriores para firmar una docena de canciones donde los géneros mantienen relaciones carnales pero sin llegar al matrimonio. La precisión de la banda y la voz indiscutible de Giammarco llevan en andas al oyente a lo largo de un disco que sabe ser lúdico y profundo. </p>
