<p>El segundo disco del reconocido cineasta ahonda en la brecha iniciada por el anterior Crazy Clown Time: una suerte de blues deconstruido por las obsesiones de un tiempo que no llegó. Con un grado de acierto desigual, la decisión de Lynch de llevar la voz cantante (en sentido literal) le resta algo de potencia al resultado final. En "I'm Waiting Here", bonus track del disco, hace una excepción y se acompaña de la joven sueca Lykke Li, cuyo registro algo naif nos deja a medio camino entre la perturbación y displicencia.
