<p>El avión se traslada en estado de suspensión o  velocidad cero, en viaje astral catatónico surcado por bandejas plásticas.  También hay momentos de velocidad pura, de fricción y delicada violencia, que  damos en llamar despegue y aterrizaje, esas transiciones torpes y rituales que  hacen a la pérdida o la recuperación de los sólidos. Pero ¿realmente se  transportan los aviones?, ¿o simplemente se trata de una sucesión de  burocracias de los espacios estancos? Marc Augé incluyó a los aeropuertos en la  categoría de no-lugares, lo cual es comprensible si nunca puso un pie en Rusia.  Allí hubiera notado que un aeropuerto no es simplemente un conjunto de  disposiciones arquitectónicas, controles policiales y (no)lugares donde administrar  esperas anónimas. Porque hay modos de habitar esos espacios de los controles, y  también hay modalidades de la espera. El aeropuerto de San Petersburgo (Санкт-Петербург,  ex Leningrado, ex Petrogrado) era lo suficientemente ruso como para lograr que  una señora alemana pusiera en evidencia su nerviosismo. Todos los hombres eran  allí Raskolnikov o algún otro personaje de Dostoievski, quizás Aliosha  Karamázov; todas las mujeres eran Anna Karenina. Princesas o trastornados  aparecían sintomatológicamente por los angostos pasillos y yo no podía dejar de  mirarlos, absorto en la contemplación de las camperas de cuero de los hombres,  las caderas de las mujeres y la extraña familiaridad de todos los viejos, que  de una u otra manera, recordaban a mis abuelos, a sus rostros. En ese  aeropuerto no hay señorita de informes; en su lugar, una <em>matrioshka</em> entrada en carnes y con actitud maternal, a quien no le  interesa demasiado hacerse entender, pero que te lleva de la mano firmemente  adonde es necesario estar. </p>
<p>La llegada a Moscú fue una loca carrera por el Metro a la una  de la mañana. Ese laberinto de estaciones es de una profundidad, de un bajo-tierra  inconcebible y las escaleras mecánicas, las lámparas, los frisos, todos los  pequeños objetos blancos y cobrizos que componen las estaciones exhiben su  estética retrofuturista de solidez soviética. Son lugares para postrarse ante  la hoz y el martillo ungiendo los óleos comunitarios marxistas-leninistas. Pero  lo importante es que llegué sin extraviarme demasiado a la casa de María, mi  primer contacto de <em>couchsurfing</em>.  Llamamos &ldquo;casa&rdquo; a la unidad habitacional existente por centenas en edificios  tipo monoblock, con escaleras sucias y oscuras, único tipo de vivienda que  parece proliferar en las urbes eslavas. Por suerte María habla inglés y  español, le gustan los juegos de mesa, España y el casamiento romántico de su  hermana con un buen muchacho de Düsseldorf. De perfil se le ve el bigote, a  María. Es linda, enfermedad que parece compartir con el resto de sus  compatriotas. Me enseña que hay que sacarse los zapatos en la entrada de la  casa, tal como ocurre en Japón. Y lo que yo quiero es llegar rápidamente a  Vladivostok, en la zona que se denomina el Lejano Este, el último bastión de  resistencia a los bolcheviques, recién conquistado en 1922, a unos cien  kilómetros de la actual Corea del Norte y con catorce husos horarios de  diferencia con Buenos aires.</p>
<p>Vladivostok  es el final o es el comienzo, allí está el monolito de los 9.288 kilómetros  del tren que recorre Rusia de lado a lado: el Transiberiano. El trazado bordea  el norte de China pasando por Khabarovsk, se interna luego en Siberia central,  recorriendo la estepa de Mongolia y bordeando el sur del lago Baikal. Desde  Irkutsk, atravesando Krasnoyarsk, llega hasta el pie de los Urales, en la  increíble Ekaterinburg donde está enterrado el zar Nicolás II, ejecutado junto  a su familia por orden de Lenin en 1918. Desde allí el tren atraviesa la  barrera geográfica que separa Asia de Europa y se interna en la zona más  densamente poblada de Rusia, hasta arribar, pocos días después, a Moscú.  Viajando en tercera clase, comparto el vagón con otras sesenta personas y  aunque cada uno tiene asignada su cama, no hay puertas ni divisiones tan  estrictas (y solamente dos baños sin duchas), así que todo es como una gran  familia. Una familia en pijama y pantuflas, un poco olorosa, rica en embutidos,  pepinillos, sonrisas curiosas, vodka, sobrepeso y uniformes militares. </p>
<p>¿Qué hacer?  Durante los quince días que toma recorrer toda la extensión continental se  imponen tres actividades principales. No hay entre ellas jerarquías ni órdenes  precisos, son más bien tres modos de la contaminación extranjera. El primero es  mediante los libros, las largas horas de tren parecen estar hechas a medida  para la literatura rusa. Quiero recomendar dos antologías imprescindibles. <em>La edad de plata</em>, una selección de  poesía rusa traducida, prologada y anotada exquisitamente por Roberto  Echavarren para su editorial La flauta mágica. Y <em>Paisaje caprichoso de la literatura rusa</em>, con traducción y  selección de Selma Ancira, prólogo de Juan Villoro y una preciosa edición del  Fondo de Cultura Económica de México que incluye el imperdible relato &ldquo;El  diablo&rdquo; de Marina Tsvietáieva y la carta que le enviara Fiódor Dostoievsky a su  hermano al día siguiente de que casi lo fusilaran y antes de partir a la cárcel  en Siberia. Luego está lo que algunos gustan denominar &ldquo;el paisaje&rdquo;, ese  continuo hipnótico al otro lado del vidrio doble, esa sucesión de pinos,  álamos, coníferas de troncos finos y largas hojas, cobrizas, amarillentas,  ocres, cortezas negras y blancas con manchas oscuras. Es otoño en Siberia. Hay  manchones de nieve de algunos días, copos tímidos que caen entre las <em>dachas</em>, las plantaciones de col y las  chimeneas fabriles. Entre tanto, el tiempo dentro del tren no registra nada de  lo que sucede en ese mundo exterior, al otro lado del vidrio. Los relojes de  todas las estaciones y de los vagones (cuando los tienen) están en horario de  Moscú, al igual que la hora de los pasajes. De tal manera que estar en el tren  es transitar en un huso horario inmune a la salida o la puesta del sol.</p>
<p>Claro está,  los compañeros de viaje, las entrañables señoras gordas, los hombres sudorosos,  las adolescentes en celo, todos aquellos que amontonados o expectantes se  transforman en fugaces cómplices de la travesía, van sedimentando hasta llegar  a los fondos de lo difícilmente olvidable. Dimitri, parco, soñador, algo así  como un buen tipo. El ucraniano de las tallas en madera. Los matones, enormes,  pelados, dientes de oro, rostros de brutos simples, ropa deportiva. El grupo de  soldados retirados completamente borrachos, que me invitaron a tomar vodka, que  se pusieron un poco violentos, rompieron mi guía de viaje mientras me acusaban  de ser un espía que quería bombardear no sé qué pueblo. El viejo, supuestamente  exagente de la KGB, que la noche anterior hacía lo posible por pegarme algún  que otro codazo, ahora llora, se me acerca, me habla. ¿Sigue borracho? Llora y  pide consuelo, me da la mano. Es duro ver llorar a un hombre recio, sentado  frente a mí me habla en su idioma incomprensible, dice cosas, me dice cosas,  sus ojos azules surcados de venas rojas, sus manos grandes y callosas. ¿Qué es  lo que en el hombre llora? ¿Lo realizado o lo nunca alcanzado? ¿Quién llora en  el hombre? Regularmente extiende su mano, cálida, y nos confortamos mutuamente.  Leo a Ana Ajmátova: &ldquo;Entre &lsquo;tener presente&rsquo; y &lsquo;venir a la memoria&rsquo; hay una  diferencia, una distancia como de Lug a un país guardado en un atlas&rdquo;.</p>
