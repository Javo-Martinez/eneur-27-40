<p>en un lugar en el que nunca he estado, felizmente más allá<br />
  de cualquier experiencia, tus ojos tienen su silencio:<br />
  en tu gesto más frágil están las cosas que me cercan,<br />
  o aquellas que no puedo tocar porque están demasiado cerca<br />
  <br />
  tu mirada más leve fácilmente puede descerrarme,<br />
  pese a que he cerrado mi ser como dedos,<br />
  tú me abres siempre pétalo por pétalo, como la Primavera abre<br />
  (tocando hábilmente, misteriosamente) su primera rosa<br />
  <br />
  o, si es tu voluntad cerrarme, yo y<br />
  mi vida se cerrarán muy hermosamente, repentinamente,<br />
  como cuando el centro de esta flor imagina<br />
  la nieve descendiendo cuidadosamente en todas partes<br />
  <br />
  Nada de lo que podemos percibir en este mundo se compara<br />
  con el poder de tu intensa fragilidad: cuya textura<br />
  me fuerza con el color de sus tierras,<br />
  mostrando muerte y eternidad con cada respiración<br />
  <br />
  (no sé qué hay en ti que se cierra<br />
  y se abre; sólo que hay algo en mí que entiende<br />
  que la voz de tus ojos es más profunda que todas las rosas)<br />
  Nadie, ni siquiera la lluvia, tiene manos tan pequeñas.</p>
