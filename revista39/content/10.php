<p>Dios se desnuda en la lluvia<br />
  como una caricia<br />
  innumerable.<br />
  Cantan los pájaros entre la lluvia.<br />
  Las plantas bailan de alegría mojada.<br />
  La tierra <br />
  como una hembra <br />
  se disuelve en los dedos penetrantes<br />
  con una palidez de mil ojos desmayados.<br />
  Camino bajo la lluvia, todo mojado, cantando, <br />
  hacia mirajes que huyen en un rumoroso sueño.<br />
  Lluvia, lluvia! <br />
  Desnudez del dios <br />
  primaveral,<br />
  que baja danzando, danzando,<br />
  a fecundar la amada<br />
  toda abierta de espera, quebrada ya de ardor<br />
  amarillo y largo.</p>
