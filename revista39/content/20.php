<p><strong>Francesca Woodman</strong>. (Denver, 1958 – New York, 1981) Sus escasos 22 años de vida le permitieron dejar varios centenares de fotografías que forman un corpus tan potente como intrigante. El blanco y negro, el formato cuadrado, un único sujeto en escena, paredes despojadas y arruinadas, cuerpos borrosos y objetos viejos son las principales herramientas con las que Woodman ha forjado su obra. En enero de 1981, decepcionada por la falta de recepción de sus fotografías, saltó desde la ventana de un edificio en Manhattan.
</p>
