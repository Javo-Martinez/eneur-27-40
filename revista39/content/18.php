<p><strong>Vivian Maier</strong>. (New  York, 1926 – Chicago, 2009) Como en un extraño juego de espejos, las  fotografías de Vivian Maier estuvieron ocultas a los ojos del mundo que  retrataron, hasta que una de esas circunstancias que cambian vidas se hizo  presente en la historia: John Maloof, buscando ilustrar un libro sobre la  historia de Chicago, dio con una caja repleta de fotografías que quedaron  latiendo en la oscuridad durante un par de años más. Según su relato, hasta la  publicación de su obituario en 2009, no había rastros ni datos sobre la niñera  profesional y fotógrafa amateur cuyas imágenes lo capturaron un par de años  después de aquella compra en busca de meras ilustraciones. De ese (re)encuentro  surgieron una página en Flickr con las primeras fotos de Maier que se abrieron  a los ojos de la gente; la aventura de rastrear más material y revelar lo que  la propia artista no había podido poner en papel por falta de dinero. Camino  que el mismo Maloof plasmó en el documental <em>Finding  Vivian Maier</em>, que tuvo un amplio reconocimiento en premios y nominaciones.  Hoy, a poco más de siete años de su muerte, las imágenes tomadas por Vivian  Maier y las palabras sobre ella/s colman la red de redes y los libros, haciendo  justicia poética sobre una obra que, en cada visita, merece ser redescubierta. </p>
