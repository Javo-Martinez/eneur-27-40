<p><strong>Patricia Verón  </strong>(Buenos Aires, 1965)</p>
<p>No entendí cómo eran las  cosas<br />
  por qué tenía una solución  igualita la historia<br />
  por qué los días  descansaban en una repetida amenaza<br />
  y lloraba ella<br />
  y él callaba<br />
  y huía mi hermano<br />
  en qué idioma hablaban<br />
  por qué esa mueca</p>
<p>nunca entendí</p>
<p>no era tan fácil aceptar<br />
  tu exacto pájaro de oro<br />
  tiritando en el piso y que  te digan<br />
  así es la vida,<br />
  Emilia</p>
