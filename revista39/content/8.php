<p><strong>Guillermo Cácharo</strong>  (Buenos Aires, 1961)</p>
<p>hay una canilla que gotea<br />
si voy a ser sincero<br />
ya no gotea ya es un  chorrito pródigo<br />
tenía ganas de escribir  que me acompaña su silbido<br />
porque junto con el agua<br />
deja escapar un susurro  ceceoso un cuchicheo<br />
escribir que me gusta  dejarla hacer su voluntad como me gusta<br />
que las hojas de los  árboles<br />
se queden en el piso se  queden se quiebren<br />
al pisarlas<br />
hasta hacerse un polvito  de papel oxidado<br />
pero recuerdo bruscamente<br />
faltará el agua en el  mundo en todas partes acá también<br />
y la responsabilidad y la  ecología<br />
y la vida todo eso<br />
así que voy a arreglar a  callar la canilla<br />
pero eso sí después a  iniciar un movimiento una campaña<br />
para salvar los susurros  cuchicheos<br />
los silbidos<br />
que faltarán también en el  mundo en todas partes</p>
