<p>Mistik – Up</p>
<p>Como un peso sin cuerpo<br />
  voy por las luces<br />
  le digo esto a ella<br />
  y me pregunta si me drogué<br />
  o estoy aún más flaca</p>
<p>me hace reír ella</p>
<p>y le digo<br />
  es el cuerpo que quema<br />
  la soledad de sus naves<br />
  siendo el que siente</p>
<p>y ella dice<br />
  que nunca lo había visto  así<br />
  y que de todas formas no  entiende<br />
  solo sabe amar algunas  horas<br />
  conocer cada cuerpo desde  un mandato antiguo<br />
  y aunque no alcance soñar  que alcanza<br />
  la realidad de algo  superior a su ser</p>
<p>le digo que<br />
  en movimientos necesarios<br />
  una condición autónoma  entre latidos<br />
  tal vez sea el cuerpo el  alma de la ofrenda</p>
<p>Hecho, quedamos así<br />
  dice ella</p>
<p> <br />
  Poemas de &ldquo;Emilia&rdquo;,  ArbolAnimal ediciones, 2014</p>
