<p><strong>El  domador de huesos (evocación del contorsionista)</strong></p>
<p align="right">&ldquo;El  domador de huesos puso<br />
  su bolsa  de tela colorada<br />
  en el  suelo, y mandó callar<br />
  a su  clavícula<br />
  que  estaba fuera de lugar&rdquo;.</p>
<p>&ldquo;Con todos estos huesos tengo que vivir&rdquo;<br />
  dijo para sí el domador de huesos.<br />
  Para vivir entero, de la cabeza<br />
  a los pies, tengo que domar estos<br />
  huesos, colocarlos a como de lugar,<br />
  porque mañana, o acaso esta noche<br />
  tenga que volver a la intemperie<br />
  mojarme como otra vez<br />
  y colocar con cuidado<br />
  cada hueso en la cajita.</p>
<p>&ldquo;Con todos estos huesos tengo que comer&rdquo;<br />
  dijo para sí el domador de huesos.</p>
<p>¿Habrá alguna vez una noche dada?<br />
  ¿Cuándo tendré calor, medio plato<br />
  en la mesa, un tercio de cuchara?</p>
<p>Y agua que no caiga del cielo.<br />
  Y sed que no la repare<br />
  el agua de la lluvia.</p>
<p>No quiero para mí<br />
  agua de lluvia,<br />
  viento de temporal<br />
  calor de fogata.</p>
<p>El fémur derecho<br />
  afectado por la humedad.<br />
  De tibia y peroné, ni hablar;<br />
  falanges entumecidas<br />
  omóplatos que ya no están<br />
  en su lugar<br />
  mientras se detiene de a ratos<br />
  la lluvia<br />
  y los huesos vuelven a girar:<br />
  el brazo que se pliega,<br />
  la pierna izquierda...</p>
<p>Un acordeón de hombre,<br />
  un fuelle humano<br />
  entrando en la cajita;<br />
  un cubo loco y transparente,<br />
  un dado eterno<br />
  girando al azar por dos monedas.</p>
  
