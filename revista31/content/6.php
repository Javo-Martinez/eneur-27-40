<p><strong>El loco  del trapecio (poema naif a las puertas del verano)</strong></p>
<p align="right">a Gustavo  Esmoris </p>
<p>No bajaré hasta que el cielo<br />
  esté abajo y la tierra arriba.<br />
  No bajaré hasta que los<br />
  de abajo estén arriba.<br />
  Hasta que los Bancos pongan<br />
  sus cuentas al servicio de la gente.<br />
  Hasta que los sicarios de nueve años<br />
  entreguen sus armas<br />
  y vuelvan sin rencor a las escuelas.<br />
  Hasta que los hombres mutilados<br />
  por las bombas se junten<br />
  y realicen la marcha de la humanidad.</p>
<p>No bajaré hasta que las fronteras<br />
  sean referencias históricas<br />
  de un pasado remoto.<br />
  Hasta que se respire aire puro.<br />
  Hasta que los transgénicos<br />
  se disuelvan en los laboratorios.<br />
  Hasta que nadie venda sus órganos<br />
  para completar un salario.<br />
  Hasta que nadie se muera infectado<br />
  por los sabores del amor.<br />
  Hasta que se sequen<br />
  los pozos de petróleo<br />
  y las selvas recuperen sus árboles.<br />
  Y los ríos<br />
  y las ciudades<br />
  y los hombres no caminen<br />
  por las rutas del cielo<br />
  contaminados.</p>
<p>No bajaré<br />
  Hasta que el tráfico humano<br />
  sea una leyenda.<br />
  Hasta que las mujeres de Juárez<br />
  vuelvan a sus casas.<br />
  Hasta que los cielos de Gaza,<br />
  Bagdad y todo medio oriente<br />
  vuelvan a ser el telón de fondo<br />
  de historias maravillosas.</p>
<p>No bajaré hasta que las sirenas<br />
  amanezcan en las orillas de la playas.<br />
  Hasta que el capitán Ulises<br />
  ate su barca negra<br />
  a los espigones de mi infancia.<br />
  Hasta que el Cid campeador llegue<br />
  una tarde de sol a mi casa<br />
  a decirme que ha vuelto a Vivar.<br />
  Hasta que caperucita roja<br />
  se coma al lobo de una vez<br />
  Y para siempre.</p>
<p>Hasta que Ovidio anuncie<br />
  En el diario del domingo<br />
  Que ha regresado del exilio.<br />
  Hasta que Sísifo talle en la roca<br />
  que lo atormenta, la imagen<br />
  victoriosa de una espada.<br />
  Hasta que la espada en la piedra<br />
  sea movida sin aspavientos<br />
  por un niño rumbo al jardín de infantes.</p>
<p>No bajaré hasta que los muertos<br />
  rompan las cruces de los cementerios.<br />
  Y en los cementerios hagan parques.<br />
  Y los parques se llenen de niños.<br />
  Y los niños llenen las paredes de dibujos.<br />
  Y en los dibujos haya pájaros.<br />
  Y esos pájaros no estén pintados,<br />
  sino golpeando con el pico<br />
  cada una de las ventanas de la imaginación.</p>
