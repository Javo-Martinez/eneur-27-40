<p><strong>Réquiem por un poeta</strong></p>
<p>Qué es mi alma, preguntas<br />
  a una imagen atado.<br />
  Es un dios en la sombra<br />
  rezándole a la sombra.<br />
  Es quizá un esclavo<br />
  lamiendo con su lengua las sobras de la vida.<br />
  La soga que en el cuello<br />
  llevábamos atada fácil es desatarla,<br />
  por cuanto es ilusión sólo, lo mismo que la vida, que el dolor y  la muerte y el sueño del dinero.<br />
  La vejez dicen sólo responde a tu pregunta.<br />
  Una piel arrugada y un hombre al que avergüenza<br />
  mirarse al sediento espejo.<br />
  Un día moriré. Un día estaré solo,<br />
  un alce cabalgando en la calle, y el aire<br />
  será para mis ojos la señal de la huida.<br />
  Ya no serán manos mis manos,<br />
  ni un solo buen recuerdo<br />
  a la vida me ligará ya entonces.<br />
  Veré pasar un niño por la acera de espanto<br />
  y le preguntaré mi nombre si mañana renazco.</p>
<p>

<strong>Contra España y otros  poemas de no amor</strong><br />
  Leopoldo María Panero<br />
1948-2014</p>
