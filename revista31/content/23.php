<p align="right">Al pueblo mapuche</p>
<p>Discípulo se acercó a Maestro y  preguntó: <br />
  –Mi hermano ha muerto, ¿por qué?<br />
  Y Maestro respondió: <br />
  –El sol se pone cada atardecer y las  mariposas vuelan un solo día –y luego calló.<br />
  Su rostro maduro fue bordado por el viento  y la frescura del aire. El pelo del color de los piñones se aferraba a sus  raíces con fuerza sobrehumana. Emanaban nervios desde sus profundidades más  férreas. Vivía en el corazón del Bosque azafrán, conviviendo con el choique, el  filú y Lafquén Trilque. Comía el alimento de los días y bebía la música de las  aves de cien voces. Se abrazaba a su natural entorno y estiraba el alma como lo  hace el arco en las manos del bello Caupolicán. El altar mantenía siempre su  llama viva y la lluvia hablaba mil lenguas que sólo él podía descifrar. El  hombre cuando está solo habla con los dioses.<br />
  Discípulo se acercó una mañana repleta  de estrellas muertas y furiosas tempestades, y dijo a Maestro: <br />
  –Mi padre ha muerto, ¿qué es la muerte? <br />
  Y Maestro habló: <br />
  –Amo demasiado la vida para temer a la  muerte. –Le ofreció una manzana y luego calló.<br />
  Con el corazón en el rostro, Discípulo  se alejó ensimismado. Tenía los ojos color canela, como las aves solitarias.  Vivía en La aldea del adiós y sonreía cuando el sol salía en el Oriente.  Danzaba y abrazaba a su perro, pintaba grandes murales donde se mostraban las  hazañas de Calfucura. La peste alejaba a sus hermanos y la oscuridad ahora era  una.<br />
  Discípulo se acercó una tarde, cuando el  cielo estaba rojo y las sombras no se dejaban ver ya. Caminó el largo camino y  se consumió en el fondo del Bosque azafrán. Miró a Maestro, que estaba  recostado y contemplaba el vuelo del cóndor, su hermano de sangre, ¡hasta él,  el volador solitario, necesita del calor de la carne, de la sangre, de la piel! <br />
  Discípulo preguntó en forma sublime: <br />
  –Mi madre ha muerto, ¿qué es la vida? <br />
  Y Maestro contestó: <br />
  –No creo que nunca llegues. <br />
  Asombrado, Discípulo volvió a preguntar: <br />
  –¿Adónde Maestro? <br />
  Entonces Maestro habló antes de  retirarse por vez postrera: <br />
  –Al origen.</p>
<p><strong><u>Glosario</u></strong><br />
  Piñón:  fruto del pehuén (araucaria).<br />
  Choique:  ñandú.<br />
  Filú:  culebra.<br />
  Lafquén  Trilque: ser mitológico que adquiere diversas formas.<br />
  Caupolicán  (piedra pulida dura como el pedernal) y Calfucura (piedra azul): grandes loncos  (caciques) que lucharon contra el invasor español, chileno o argentino, dando  su vida por la libertad de su pueblo.</p>
