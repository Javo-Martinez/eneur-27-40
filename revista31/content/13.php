<p>De las muchas propagaciones en ondas que pueden  encontrarse en la naturaleza, la luz y el sonido son la esencia y la materia de  gran parte de la producción artística que el hombre ha ido concibiendo a lo  largo de su historia. La música, la plástica, la fotografía y el cine,  combinación de ambas propagaciones en el espacio, ponen de manifiesto estos  fenómenos físicos a los cuales los simples mortales sólo nos dedicamos a  disfrutar. Siguiendo la tradición de nuestros Breves, un salpicado de luz en  forma de tracks que no alcanza para concluir absolutamente nada sino dejar  algún hilo suelto de curiosidad del cual el lector/oyente pueda tirar para su  propio placer.</p>

