<p>Nicanor Parra Sandoval nació en septiembre de 1914 en San Fabián de Alico, cerca de la ciudad de Chillán, en el centro geográfico de Chile. La vida lo llevaría desde las primeras publicaciones en publicaciones estudiantiles hasta ser uno de los grandes referentes de la poesía sudamericana contemporánea; forjando a fuerza de originalidad y desparpajo el campo de la antipoesía como el lugar fértil en el que crecieron sus palabras; a la sombra de sus viajes a Estados Unidos e Inglaterra; siendo el mayor de los nueve hermanos de una familia que también le dio al mundo a otra artista de la estatura de su hermana Violeta Parra. &quot;Volvería a escribir lo que he escrito / 
  Por supuesto Sras. &amp; Sres. / 
  Claro que reservándome el derecho / 
  A modificar el fondo &amp; la forma&quot;; escribió en 1997. No es una declaración principios sino, lisa y llanamente, la materia prima de todas sus palabras antipoéticas.</p>
