<p><strong>Los rubios</strong><br />
  <br />
  Llegaron en una sábana &ldquo;hotel palmeras&rdquo;<br />
  uno con otro en el rigor extremo.<br />
  Habrá que romperlos para separarlos<br />
  buscarles el hígado.<br />
  <br />
  Primero ella<br />
  con esos huesitos de pájaro.<br />
  No habrá sangre<br />
  en la apertura del cierre frontal.<br />
  <br />
  Sus huellas dactilares dirán Eva<br />
  quince, dieciséis<br />
  el embarazo de siete semanas en caída.<br />
  Por él hago mi apuesta Matías o Guillermo<br />
  estudios incompletos<br />
  una madre un padre que nunca.<br />
  <br />
  Pena. Los rubios envejecen más suave.<br />
  Una bendición el recesivo<br />
  entre tantos ángeles oscuros.</p>
