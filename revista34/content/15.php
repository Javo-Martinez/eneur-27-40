<p>Se dice muy a menudo que el  silencio es una sustancia de lo más nociva y que hay que sacarlo todo afuera,  exorcizar y mandar a la cucha al diablo del secreto. En este contexto, y en un  intento por generar confianza en los inversores, los editores de esta revista  han decidido comenzar a confesar lo inconfesable, aquellos gustos e  inclinaciones arrinconados en el cerebelo y que únicamente encuentran  justificación en que el tiempo pasa y nos vamos poniendo tecnos.<br />
En esta ocasión, una fuerte  tormenta urbana desató el acercamiento entre dos amigos que se vieron venir la  noche y exclamaron mirando para arriba: &ldquo;El cielo es too much&rdquo;.</p>

