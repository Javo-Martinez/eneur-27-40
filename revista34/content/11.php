<p>Al  año 2014, que ya nos está mostrando las últimas hilachas de su espalda, vamos a  concederle el beneplácito de un adjetivo comodín, el que cada uno quiera  ponerle según las vicisitudes que su vida le haya querido conceder. Pero si  hacemos un repaso breve al calendario musical, seguramente podamos dibujar una  sonrisa. Son muchos y buenos los nombres que nos han dejado escuchar sus  novedades artísticas, las cuales vinieron a confirmar que, si bien no solo de  música vive el hombre, perfectamente esta puede estimular el entusiasmo o acompañar  a la incertidumbre o convertirse en ese elemento neutro y esencial que gestiona  el <em>horror vacui</em> que se produce  mientras esperamos que hiervan los fideos y no podemos pensar en otra cosa.</p>
<p>Un  día de finales de febrero de este año, el señor Francisco Sánchez Gómez tuvo un  dolor en el pecho mientras paseaba por la mexicana Playa del Carmen. Por  desgracia, el hombre fatalmente infartado entró enseguida en la inmortalidad  bajo el nombre de Paco de Lucía, sin siquiera sospechar que su ingreso  celestial constituía en sí misma una redundancia. Antes de morir, Paco había  dejado terminado <em>Canción andaluza</em>, su  disco póstumo del que proviene esta hermosa &ldquo;María de la O&rdquo;.<br />
