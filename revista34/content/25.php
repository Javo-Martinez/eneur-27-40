<p><strong>De pena  y las hilachas</strong></p>
<p>Ya veré<br />
  La esparta tejiendo<br />
  Temblores de trama<br />
  Del aire<br />
  Un latir <br />
  Nada abstracto<br />
  En telas salvajes y esperas <br />
  Y un malón de malones de tus ojos<br />
  Enhebran polvaredas<br />
  Todo seco todo cactus<br />
  En la urdimbre del ladrido<br />
  Embozado, sin el morir<br />
  De pena y las hilachas<br />
  Por nacer postergado<br />
  La noche del día que nos dejamos<br />
  De empezar a veré.</p>
