<p><strong>Pero  apenas defenso</strong></p>
<p>La voz del volver me canta<br />
  Sola al oído de rejas<br />
  Un oratorio al desierto<br />
  Al orden de sus arenas<br />
  Inmovedizas<br />
  Que cubren de sombra los versos<br />
  Las marcas en la piel<br />
  El tajo flamante de rojo <br />
  De sangre de un estreno.<br />
  Todas las horas<br />
  Que la herida sepa soportar<br />
  Sobre sus bordes generosos<br />
  Serán bienvenidas<br />
  Al igual que se acuna<br />
  Al espanto en cada goce<br />
  La lumbre en cada tiniebla<br />
  O el firmamento en el olvido<br />
  Como un secreto guardado entre las rocas<br />
  Pero apenas defenso<br />
  De la intemperie del otro<br />
  Y sin embargo con un rastro de ancestros<br />
  Que lo acabaría fundiendo al sinfín.</p>
