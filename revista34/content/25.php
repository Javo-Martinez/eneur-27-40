<p><strong>Que  queda por ausentarse</strong></p>
<p>Del abrazo un suspiro de lago<br />
  Sus aguas amansan<br />
  Por encima del sueño salobre<br />
  Desvalido del almíbar<br />
  Un aljibe más del desvelo<br />
  Que desagua sobre tus cuerpos<br />
  Siempre fugados<br />
  Sin la forma de las yemas<br />
  Sin hundirse en lo hondo<br />
  Siempre yéndose cuerpos<br />
  Barco a barco<br />
  Siempre la espuma hundiendo a la vigilia<br />
  Aunque parezca mentira.</p>
<p>Luego nada más que agua<br />
  Dulce acaso todo lo demás<br />
  Que queda por ausentarse<br />
  Tus cuerpos nos helamos<br />
  A bosques de distancia<br />
  Más allá de la estampida<br />
  Si apenas fuimos cada apenas<br />
  Mientras tanto <br />
  Todo el tiempo fue siendo entonces<br />
  Y tus cuerpos volvimos a faltar<br />
  Con la cortesía del aterido<br />
  Pidiendo clemencia a la fiebre<br />
  Por no haber sido abrazados.</p>
