<p>Para confrontar, desvalorizar, ridiculizar o ganar un minuto de fama,  tanto políticos como actores, y seres mediáticos en general, pueblan los medios  de comunicación brindándonos uno de los espectáculos más lamentables que la  condición humana nos pueda ofrecer. Si por lo menos lo hicieran con gracia, o  con altura, podríamos divertirnos o entretenernos, pero lamentablemente eligen  un estilo burdo, grosero y desmedidamente agresivo que nos transmite la idea de  que todo vale si el fin es permanecer en boca de la gente, casi con afán de ser  deglutidos por la morbosidad latente en el televidente medio.</p>
<p>Por suerte, la historia de la literatura nos otorga momentos ejemplares  en donde estos menesteres de burlarse del otro eran abordados con altura y  exquisitez.</p>
<p>En este diálogo poético entre Quevedo y Góngora, el lector atento encontrará,  no sin esfuerzo, las burlas más  infames:  Quevedo diciendo de Góngora que es un judío renegado, bufarrón, amante del culo  y Góngora tratando a Quevedo de rengo, ciego y bruto. Un derroche de estilo y un  juego de palabras que nos muestran que entre la bajeza y la altura existe una  distancia muy difícil de medir…</p>
<p>&nbsp;</p>
<p><strong>Quevedo</strong><u> </u><br />
  <em>&ldquo;Quevedo contra Góngora&rdquo;</em><br />
  Yo te untaré  mis obras con tocino,<br />
  Porque no me  las muerdas Gongorilla,<br />
  Perro de los  ingenios de Castilla,<br />
  Docto en  pullas, cual mozo de camino.</p>
<p>Apenas hombre,  sacerdote indino,<br />
  Que aprendiste  sin christus la cartilla<br />
  Chocarrero de  Córdoba y Sevilla<br />
  Y en la corte,  bufón a lo divino.</p>
<p>¿Por qué  censuras tú la lengua griega<br />
  Siendo sólo  rabí de la judía,<br />
  Cosa que tu  nariz aún no lo niega?</p>
<p>No escribas  versos más, por visa mía;<br />
  Aunque aquesto  de escribas se te pega,<br />
  Por tener de  sayón la rebeldía.</p>
<p>&nbsp;</p>
<p><strong>Góngora</strong><u>:</u><br />
  <em>&ldquo;A don francisco de Quevedo&rdquo;</em><br />
  Anacreonte  español, no hay quien os tope<br />
  Que no diga  con mucha cortesía,<br />
  Que ya que  vuestros pies son de elegía,<br />
  Que vuestras  suavidades son de arrope.</p>
<p>¿No imitaréis  al terenciano Lope,<br />
  Que al de  Belerofonte cada día<br />
  Sobre suecos  de cómica poesía<br />
  Se calza  espuelas, y le da un galope?</p>
<p>Con cuidado  especial vuestros antojos<br />
  Dicen que  quieren traducir al griego,<br />
  No habiéndolo  mirado vuestros ojos.</p>
<p>Prestádselos  un rato a mi ojo ciego,<br />
  Porque a luz  saque ciertos versos flojos,<br />
  Y entenderéis  cualquier gregüesco luego.</p>
<p>&nbsp;</p>
<p><strong>Quevedo</strong>:<br />
  <em>&ldquo;Contra Luis de Góngora y su poesía&rdquo;</em><br />
  Este cíclope,  no siciliano, <br />
  del microcosmo  sí, orbe postrero;<br />
  esta antípoda  faz, cuyo hemisferio<br />
  zona divide en  término italiano;</p>
<p>este círculo  vivo en todo plano;<br />
  este que,  siendo solamente cero,<br />
  le multiplica  y parte por entero<br />
  todo buen  abaquista veneciano;</p>
<p>el minóculo  sí, mas ciego vulto;<br />
  el resquicio  barbado de melenas;<br />
  esta cima del  vicio y del insulto;</p>
<p>este, en quien  hoy los pedos son sirenas,<br />
  éste es el  culo, en Góngora y en culto,<br />
  que un  bujarrón le conociera apenas.</p>
