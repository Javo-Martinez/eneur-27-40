Para Navidad pedía muchísimos regalos, una lista interminable. Pero Papá Noel no le daba el gusto: sólo un par de medias. Y así fue como Bradley tramó una trampa para Papá Noel que, por suerte para los buenos niños, no tuvo el resultado deseado.<br />

