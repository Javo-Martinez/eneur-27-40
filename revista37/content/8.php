<strong>Miguel Ángel Asturias</strong>
<p><strong>Ulises</strong><br />
  Íntimo amigo del ensueño, Ulises <br />
  volvía a su destino de neblina, <br />
  un como regresar de otros países <br />
  a su país. Por ser de sal marina. <br />
  Su corazón surcó la mar meñique <br />
  y el gran mar del olvido por afán, <br />
  calafateando amores en el dique <br />
  de la sed que traía. Sed, imán. <br />
  Aguja de marear entre quimeras <br />
  y Sirenas, la ruta presentida <br />
  por la carne y el alma ya extranjeras. <br />
  Su esposa lo esperaba y son felices <br />
  en la leyenda, pero no en la vida, <br />
porque volvió sin regresar Ulises.</p>
<p>&nbsp;</p>
<p><strong>Es el caso de hablar</strong><br />
  Madre, te bendigo porque supiste hacer <br />
  de tu hijo un hombre real y enteramente humano. <br />
  Él triunfará en la vida. Se marcha y es el caso <br />
  de hablar de su regreso. Cuando veas volver, <br />
  en un día de fiesta, un viador que en la mano <br />
  luzca preciosas joyas y haga notorios paso <br />
  y ademán -¿insolencia, dinero o buena suerte?-; <br />
no salgas a su encuentro, puede no ser tu hijo. </p>
<p>Madre, si mirando el camino se acongoja tu alma <br />
  y tras la tapia asoma entonces un caminante <br />
  que trae gran renombre, espada poderosa, <br />
  ceñidas armaduras, en la frente la palma <br />
  de la victoria, y gesto de sigamos adelante, <br />
  por mucho que eso valga vale muy poca cosa <br />
  el poder de la espada, el oro y el renombre; <br />
  no salgas a su encuentro, puede no ser tu hijo. </p>
<p>Madre, si aspirando el aroma de una flor <br />
  en un día de otoño gris y meditabundo <br />
  oyes que alguien te llama y te dice: ¡Señora, <br />
  allá por el camino viene un gran señor <br />
  del brazo de su amada, conoce todo el mundo, <br />
  en la pupila clara trae la mar que añora <br />
  y en su copa de mieles un sabor de aventura!; <br />
  no salgas a su encuentro, puede no ser tu hijo. </p>
<p>Madre, si en el invierno, después de haber cenado, <br />
  estás junto al bracero pensando con desgano, <br />
  oídos a la lluvia que cae sobre el techo, <br />
  y en eso, puerta y viento... Es alguien que ha <br />
  entrado <br />
  descubierta la frente y herramienta en la mano, <br />
  levántate a su encuentro porque tienes derecho <br />
  de abrazar a tu hijo, de quien hiciste un hombre <br />
  que vuelve de la vida con el jornal ganado.</p>
<p>&nbsp;</p>
<p><strong>Invierno</strong><br />
  En rodillas de viento, galgo y huella <br />
  fui tras de ti, mujer en mi presencia <br />
  transportado por ágil luz de estrella <br />
  de sentido en sentido hasta la ausencia. <br />
  Atravesaste, amor, los egoísmos <br />
  que en sílice de lágrimas desvelo <br />
  yuxtaponiendo abismos sobre abismos <br />
  en mi insoluble soledad de hielo. <br />
  La gran araña de la lluvia teje <br />
  con agua y viento telarañas móviles <br />
  ¿qué mañana serán cuando despeje? <br />
  Superficie de vidrio sin quebranto, <br />
  como serán mis ojos cuando inmóviles <br />
hayan llorado ya todo su llanto.</p>
<p>&nbsp;</p>
<p><strong>Credo</strong><br />
  Credo en la Libertad, Madre de América <br />
  creadora de mares dulces en la tierra, <br />
  y en Bolívar, su hijo, Señor Nuestro <br />
  que nació en Venezuela, padeció <br />
  bajo el poder español, fue combatido, <br />
  sintióse muerto sobre el Chimborazo, <br />
  resucitó a la voz de Colombia, <br />
  tocó al Eterno con sus manos <br />
  y está parado junto a Dios. <br />
  No nos juzgues, Bolívar, antes del día último, <br />
  porque creemos en la comunión de los hombres <br />
  que comulgan con el pueblo, sólo el pueblo <br />
  hace libres a los hombres, proclamamos <br />
  guerra a muerte y sin perdón a los tiranos <br />
  creemos en la resurrección de los héroes <br />
  y en la vida perdurable de los que como Tú, <br />
Libertador, no mueren, cierran los ojos y se quedan  velando.</p>
