<p>Cuando promediaba la edición de este número  murió en España Carmen Balcells, editora reconocida por haber puesto sus bazas  en escritores latinoamericanos que no tenían mayor penetración en los cánones  culturales. El caballito de batalla fue, ni más ni menos, que el realismo  mágico tan prolijamente edificado por Gabriel García Márquez, quizás el pollo  de Balcells que más reconocimientos, premios y récords de venta obtuvo de la  mano de la catalana. Seguramente, su muerte será el disparador de panegíricos y  críticas, de las evocaciones que, afortunadamente, nunca comienzan ni terminan  en el mismo lugar. Esta suerte de hada madrina del llamado <em>boom</em> latinoamericano ha despertado simpatías y odios, ya que no se  privó de ninguna artimaña a la hora de hacer valer su posición. Para el devenir  de la historia quedará revisar, o no, los efectos de su ida del mundo. Mientras  tanto, creímos que era una buena idea juntar en una páginas las palabras de su  más poderoso tridente en poesía: Pable Neruda, Vicente Aleixandre y Miguel  Ángel Asturias; pichones de poetas...</p>
