<p><strong>Vicente Aleixandre</strong></p>
<p><strong>Tristeza o pájaro</strong><br />
  Esa tristeza pájaro carnívoro; <br />
  la tarde se presta a la soledad destructora; <br />
  en vano el río canta en los dedos o peina, <br />
  peina cabellos, peces, algún pecho gastado. </p>
<p>Esa tristeza de papel más bien basto; <br />
  una caña sostiene un molinillo cansado; <br />
  el color rosa se pone amarillo, <br />
  lo mismo que los ojos sin pestañas. </p>
<p>El brazo es largo como el futuro de un niño; <br />
  mas para qué crecer si el río canta <br />
  la tristeza de llegar a un agua más fuerte, <br />
  que no puede comprender lo que no es tiranía. </p>
<p>Llegar a la orilla como un brazo de arena, <br />
  como niño que ha crecido de pronto <br />
  sintiendo sobre el hombro de repente algún pájaro. <br />
  Llegar como unos labios salobres que se llagan. </p>
<p>Pájaro que picotea pedacitos de sangre, <br />
  sal marina o rosada para el pájaro amarillo, <br />
  para ese brazo largo de cera fina y dulce <br />
  que se estira en el agua salada al deshacerse</p>
<p>&nbsp;</p>
<p><strong>Como el ayer</strong> <br />
  ¿Oyes su voz? Palabras son, y mudas.<br />
  ¿Oyes el mar? Oleada es de silen­cio. Y tiempo,<br />
  espuma.<br />
  Pero mirar su voz, oír su mirar, sentir la sombra,<br />
  besar el aire que agitó: es dor­mir. Yo velo,<br />
  velo tu fugitivo estar, que inmó­vil es, y es ido.<br />
  Hermoso es el rumor de o que el alma pide o<br />
  tuvo y  sigue estando.<br />
  Como el ayer, que dura, y ya es mañana.<br />
  Hoy tú, presente ayer. Y nunca.</p>
<p>&nbsp;</p>
<p><strong>Son bordes</strong> <br />
  Son bordes  del vivir: un cuerpo lícito.<br />
  No como nube. Quizá más piedra que ondea.<br />
  Más que sonido o aire. No, espu­ma.<br />
  Pues fugitivo rueda entre las aguas,<br />
  corre y narra, y se va gastando a solas.<br />
  Como ése, como aquél, piedras rodadas<br />
  que lentas se hacen semejantes<br />
y que igual al fin, y van al mar.</p>
<p>&nbsp;</p>
<p><strong>Vida final</strong> <br />
  Quietas, pero más vivas.<br />
  La memoria final comporta un hu­mo.<br />
  Rara especie de amor que envuelve o borra.<br />
  Como unos ojos grandes desleídos<br />
al fin entre puras palabras.</p>
<p>Suenan voces, hay gestos.</p>
<p>El corazón da fe, pero sólo de un orden.<br />
  Es un orden oscuro, perpetrado, entendido.<br />
Por las venas escapa, pero siem­pre volviendo.</p>
<p>Fuese una fuente clara,<br />
  la sangre,<br />
  donde el agobio o carga se lavase pasando.<br />
  Al volver reluciese, como túnica leve transparente<br />
  a otras luces.<br />
  Pero la sangre emite su canción serpentina.<br />
  Y entre el limo se enrosca, nos recorre y aflora<br />
  con los ojos muy tristes. Sangre muda que pasa.</p>
<p>Con los años más lenta; pero sangre encendida<br />
  que en la noche es más gruesa.<br />
  Casi ahogada en anillos: por el pecho sus nudos.<br />
  Ah, cuán frío el aliento que rozó sus escamas.<br />
  Cuán finados los besos de esos labios impuros.</p>
