<p><strong>Pablo Neruda</strong></p>
<p><strong>Hoy cuántas horas…</strong> <br />
  Hoy cuántas horas van cayendo<br />
  en el pozo, en la red, en el tiempo:<br />
  son lentas pero no se dieron tre­gua,<br />
  siguen cayendo, uniéndose<br />
  primero como peces,<br />
  luego como pedradas o botellas.<br />
  Allá abajo se entienden<br />
  las horas con los días,<br />
  con los meses,<br />
  con borrosos recuerdos,<br />
  noches deshabitadas,<br />
  ropas, mujeres, trenes y provin­cias,<br />
  el tiempo se acumula<br />
  y cada hora<br />
  se disuelve en silencio,<br />
  se desmenuza y cae<br />
  al ácido de todos los vestigios,<br />
  al agua negra<br />
de la noche inversa.</p>
<p>&nbsp;</p>
<p><strong>XII</strong><br />
  Dame la mano desde la profunda <br />
  zona de tu dolor diseminado. <br />
  No volverás del fondo de las rocas. <br />
  No volverás del tiempo subterráneo. <br />
  No volverá tu voz endurecida. <br />
  No volverán tus ojos taladrados. <br />
  Mírame desde el fondo de la tierra, <br />
  labrador, tejedor, pastor callado:<br />
  domador de guanacos tutelares:<br />
  albañil del andamio desafiado:<br />
  aguador de las lágrimas andinas:<br />
  joyero de los dedos machacados:<br />
  agricultor temblando en la semilla:<br />
  alfarero en tu greda derramado:<br />
  traed a la copa de esta nueva vida <br />
  vuestros viejos dolores enterrados. <br />
  Mostradme vuestra sangre y vuestro surco, <br />
  decidme: aquí fui castigado, <br />
  porque la joya no brilló o la tierra <br />
  no entregó a tiempo la piedra o el grano:<br />
  señaladme la piedra en que caísteis <br />
  y la madera en que os crucificaron, <br />
  encendedme los viejos pedernales, <br />
  las viejas lámparas, los látigos pegados <br />
  a través de los siglos en las llagas <br />
  y las hachas de brillo ensangrentado. <br />
Yo vengo a hablar por vuestra boca muerta.</p>
<p>A través de la tierra juntad todos <br />
  los silenciosos labios derramados<br />
  y desde el fondo habladme toda esta larga noche <br />
  como si yo estuviera con vosotros anclado, <br />
  contadme todo, cadena a cadena, <br />
  eslabón a eslabón, y paso a paso, <br />
  afilad los cuchillos que guardasteis, <br />
  ponedlos en mi pecho y en mi mano, <br />
  como un río de rayos amarillos, <br />
  como un río de tigres enterrados, <br />
  y dejadme llorar, horas, días, años, <br />
  edades ciegas, siglos estelares.</p>
<p>Dadme el silencio, el agua, la esperanza.</p>
<p>Dadme la lucha, el hierro, los volcanes.</p>
<p>Apegadme los cuerpos como imanes.</p>
<p>Acudid a mis venas y a mi boca.</p>
<p>Hablad por mis palabras y mi sangre.</p>
<p>&nbsp;</p>
<p><strong>El insecto</strong><br />
  De tus caderas a tus pies<br />
  quiero hacer un largo viaje.</p>
<p>Soy más pequeño que un insecto.</p>
<p>Voy por estas colinas,<br />
  son de color de avena,<br />
  tienen delgadas huellas<br />
  que sólo yo conozco,<br />
  centímetros quemados,<br />
  pálidas perspectivas.</p>
<p>Aquí hay una montaña.<br />
  No saldré nunca de ella.<br />
  ¡Oh qué musgo gigante!<br />
  ¡Y un cráter, una rosa<br />
  de fuego humedecido!</p>
<p>Por tus piernas desciendo<br />
  hilando una espiral<br />
  o durmiendo en el viaje<br />
  y llego a tus rodillas<br />
  de redonda dureza<br />
  como a las cimas duras<br />
  de un claro continente.</p>
<p>Hacia tus pies resbalo,<br />
  a las ocho aberturas<br />
  de tus dedos agudos,<br />
  lentos, peninsulares,<br />
  y de ellos al vacío<br />
  de la sábana blanca<br />
  caigo buscando ciego<br />
  y hambriento tu contorno<br />
  de vasija quemante.</p>
<p>&nbsp;</p>
<p><strong>Sabor</strong><br />
  De falsas astrologías, de costumbres un tanto lúgubres,<br />
  vertidas en lo inacabable y siempre llevadas al lado,<br />
he conservado una tendencia, un sabor solitario.</p>
<p>De conversaciones gastadas como usadas maderas,<br />
  con humildad de sillas, con palabras ocupadas<br />
  en servir como esclavos de voluntad secundaria,<br />
  teniendo esa consistencia de la leche, de las semanas  muertas,<br />
  del aire encadenado sobre las ciudades.</p>
<p>¿Quién puede jactarse de paciencia más sólida?<br />
  La cordura me envuelve de piel compacta<br />
  de un color reunido como una culebra:<br />
  mis criaturas nacen de un largo rechazo:<br />
  ay, con un solo alcohol puedo despedir este día<br />
  que he elegido, igual entre los días terrestres.</p>
<p>Vivo lleno de una sustancia de color común, silenciosa<br />
  como una vieja madre, una paciencia fija<br />
  como sombra de iglesia o reposo de huesos.<br />
  Voy lleno de esas aguas dispuestas profundamente,<br />
  preparadas, durmiéndose en una atención triste.</p>
<p>En mi interior de guitarra hay un aire viejo,<br />
  seco y sonoro, permanecido, inmóvil,<br />
  como una nutrición fiel, como humo:<br />
  un elemento en descanso, un aceite vivo:<br />
  un pájaro de rigor cuida mi cabeza:<br />
  un ángel invariable vive en mi espada.</p>
