<p><span class="image_cen1"><img src="images/124.jpg"></span>Si volvemos al año 1973, los amigos de Led Zeppelin se encontraban estrenando un long play que le volaría la peluca a más de uno: Houses of the Holy, el último de la banda con el sello Atlantic, antes de fundar el suyo propio Swan Song Records. En el lado A del disco, que largaba con la mítica The Song Remains the Same, la emprendieron con el tema de la colina y fueron un poco más allá, con una lírica en la que la voz cantante reconoce en una mujer a la poseedora del amor que necesita y la convoca a andar juntos por los caminos mientras, a modo de confesión de partes, recorre tiempos de amor, tiempos de amargura, mentiras dichas y deseos varios.</p>



