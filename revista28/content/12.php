<p><span class="image_cen1"><img src="images/123.jpg"></span>En el año 1977, Ian Gillan, ya por fuera de Deep Purple y antes del regreso anunciado a una de las bandas que marcaron la cancha que se extiende desde el rock progresivo al heavy metal, editó, con más penas que glorias, el disco Clear Air Turbulence. Tal es así que ni el mismísimo pelilargo londinense pudo escaparse de las redes de ese modo de hacer música. En su versión sobre lo que puede dar la cima de la colina asegura que llevó mil siglos recordar y otros mil olvidar la llegada del Mesías, en una lírica en que se entreveran las críticas al poder, lo que se hace con la hambruna y el enfrentamiento en el que el hombre es lobo del hombre. Porque como bien dice, el ser humano vino al mundo a pecar…</p>


