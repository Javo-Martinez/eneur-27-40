<p>Desde que el hombre es hombre religioso, las elevaciones del terreno  geográfico han representado un acercamiento a todas las divinidades que, a lo  largo de la historia del mundo, fueron colocadas simbólicamente en ese espacio  llamado cielo. No es en este recorrido musical en el que se develará cómo los  primeros textos que el hombre creó establecieron los espacios de lo divino, lo  mundano y lo pecaminoso. Apenas se trata de disfrutar de las trazas que el  góspel, de las últimas composiciones musicales religiosas por excelencia, ha  dejado al subir la colina. Esa en la que casi, casi nada nos resulta pasajero…</p><br />


<p><span class="image_cen1"><img src="images/121.jpg"></span>Agnes Obel es una cantautora danesa de poco más de 30 años de edad que  alcanzó el éxito en su Dinamarca natal con un álbum editado en 2010, llamado  Philarmonics, el que incluyó una melancólica canción con una espera en una  colina; un llamado amoroso que previene de la negrura de la ausencia.  Compositora de todos los temas a excepción de un cover de John Cale y  productora de su propio sonido, reconoce entre sus influencias a Jan Johansson,  Erik Satie, P. J. Harvey, Claude Debussy y Roy Orbison, entre otros. Mix que le  da un bonus adicional a la curiosidad por escucharlo.</p>


