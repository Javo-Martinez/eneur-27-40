<p style="text-align:left">Quiero decirlo ahora <br />
  porque si no después las cosas se complican. <br />
  Soy peor todavía de lo que muchos creen. <br />
  Me gusta justamente el plato que otro come <br />
  aburro una tras otra mis camisas <br />
  me encantan los entierros y odio los recitales <br />
  duermo como una bestia <br />
  deseo que los muebles estén más de mil años en el mismo lugar <br />
  y aunque a escondidas uso tu cepillo de dientes <br />
  no quiero que te peines con mi peine. <br />
  Te explico estas cuestiones <br />
  porque si todo vuelve a comenzar <br />
  no me hagas mucho caso acuérdate.</p>
