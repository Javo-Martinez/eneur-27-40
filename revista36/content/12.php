  <p> <strong>Illinois ¬ Sufjan Stevens<br />
    2005 – Asthmatic Kitty/Secretly Canadian and Rough Trade</strong><br />
    Una propuesta arriesgada que Sufjan Stevens traduce en melodías, remansos  armónicos, distorsiones y zumbidos, todo de lo que no estamos exentos en este  mundo. El disco tiene acción residual: se agranda de principio a fin; crece en  las escuchas sucesivas y tiene puntos altísimos que producen unas enormes ganas  de ir a por más: dejarse seducir por el viaje sónico y degustar un disco que es  como una golosina muy fina.
