  <p> <strong>Divididos por la felicidad<br />
    1985 – CBS</strong><br />
    Buenos Aires ardía por la recuperación de la democracia y Luca Prodan por la  recuperación de su adicción a la heroína que lo llevó a recalar en las costas  de Buenos Aires. Primer disco de Sumo, una de las dos bandas que partirían las  aguas del rock nacional, fue la hendija por la que ingresó el estrafalario  cantante italiano al mundo simbólico criollo que no sería el que es sin el aporte  de su irreverencia. Ese mismo año, en otras latitudes no tan lejanas, Patricio Rey y sus Redonditos de Ricota editaban su disco debut Gulp!... </p>
