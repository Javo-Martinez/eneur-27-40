  <p> <strong>Help! ¬ The Beatles<br />
    1965 – Capitol Records</strong><br />
    En el mismo año que produjeron  ese disco  bisagra llamado Rubber Soul, los Fabs Four le dieron al mundo el álbum Help!  que además del desgarrado pedido de ayuda de John Lennon incluyó temazos como  The Night Before, You’ve Got to Hide your Love Away, Ticket to Ride y  Yesterday, el tema más versionado de la historia de la música. La película que  acompañó el lanzamiento del disco fue un ícono en la cultura pop que giraba  alrededor de un increíble anillo que el bueno de Ringo portaba en una de sus  manos.<br />
