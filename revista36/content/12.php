  <p> <strong>Mellon Collie &amp; The Infinite  Sadness ¬ The Smashing Pumpkins<br />
    1995 – Virgin Records</strong><br />
    Número uno en varios charts y ganador de varios discos de platino por su  explosión de ventas, el tercer álbum de la banda de Chicago es una colección de  28 temas que exploran otra tanta cantidad de sonidos y posibilidades de  composición musical. Evidentemente marcado por un título que incluye la  melancolía y la tristeza, tiene un paisaje sonoro ecléctico apoyado en la voz  de Billy Corgan y con más espacios para la guitarra de James Iha y el bajo de  D’Arcy, lo que constituyó un renacimiento estético y uno de los puntos  culminantes de la banda.
