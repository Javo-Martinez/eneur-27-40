<p>Dado que la manteca no ha sido  inspiración de muchos músicos y que quemamos las naves en otra sección de  la revista, decidimos que a mal puerto nos llevaría forzar el parentesco entre  estas breves grageas y nuestro número 36 y se nos dio por estos de los  aniversarios y cumpleaños y decidimos hacer un recorrido por el tiempo, celebrando las tantas décadas de unos tantos discos. Y sí: de música hay que  vivir.</p>
