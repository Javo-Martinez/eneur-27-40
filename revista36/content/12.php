  <p> <strong> Wish you were here ¬ Pink Floyd<br />
    1975 – EMI </strong><br />
    Más de siete años le llevó a una de las mejores bandas de la historia poder  procesar la despedida de Syd Barret, el diamante loco que en los primeros pasos  fue uno de los pilares estéticos de Floyd. Adelantando lo que vendría se  entrevera por las exploraciones por la melancolía, la locura y el <em>rock bussiness</em>. En términos estéticos,  significó una torsión conceptual con un álbum que abre y cierra con la misma  canción y cuyas partes se unen a través de las distintas composiciones que  completan este precioso disco.
