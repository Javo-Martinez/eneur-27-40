<p>A pesar de mi ya vieja devoción por los grandes  modernistas brasileños (especialmente Carlos Drummond de Andrade, Murilo Mendes  y Manuel Bandeira), a los que vengo divulgando en forma sostenida desde mi  adolescencia, durante mucho tiempo no me animé a intentar la traducción al  castellano de la poesía del insigne Mário de Andrade. Y no solo por admiración,  o por respeto. Ya en otras ocasiones me fue dado afirmar públicamente que la  suya no es solo una personalidad ejemplar sino también directamente  paradigmática dentro de ese singular movimiento: el modernismo brasileño, que  por no dejar de ser a la vez auténticamente nacional y profundamente  vanguardista, pudo testimoniar a partir de febrero de 1922, desde aquella  legendaria Semana de Arte Moderno realizada en São Paulo (como el gran César  Vallejo lo hacía, magníficamente, también ese mismo año en el Perú, en  Trujillo, publicando su inconformista <em>Trilce</em>), la absoluta originalidad  y hondura del vanguardismo latinoamericano que, tanto no era en absoluto  epígono —como ya había demostrado en la década anterior, con su gestión pionera  en la propia Europa, el chileno Vicente Huidobro—, que se adelantaba por  ejemplo al primer número de &ldquo;La   Revolución surrealista&rdquo; y al &ldquo;Primer Manifiesto del  Surrealismo&rdquo;, ambos aparecidos en octubre de 1924.</p>
<p>Una de las características en ese aspecto muy definidas y  que hacen a la raigal originalidad del modernismo brasileño fue la especial  atención que sus participantes prestaron a la resonancia de su identidad  nacional, a la vez tan espléndidamente mestiza y tan nítidamente marcada, y de  manera muy especial a la cuestión del idioma nacional, del idioma entendido no  como adaptación a un modelo pretendido como eterno e invariable sino como una  auténtica lengua viva, orgánicamente viva, embebida de vida, traspasada por la  vida y abierta por lo tanto ineludiblemente a las vicisitudes y también a las  vidas de los hombres bien concretos que lo hablaban.</p>
<p>De esa actitud, antes experimentada como necesidad  existencial que como teoría apenas, pero también asumida intelectualmente,  racionalmente, con toda inteligencia fue claro ejemplo lo mejor de la  producción del modernismo brasileño pero, de modo muy singular, la de Mário de  Andrade, nacido en São Paulo el 9 de octubre de 1893 y fallecido allí mismo  (¿dónde, si no?) el 25 de febrero de 1945. Su capacidad de invención  lingüística, y no solo fonética sino también hasta ortográfica, que no es otra  cosa que su fidelidad a la misma riqueza viviente del habla de sus paisanos, se  puso de manifiesto en su escritura con tanta originalidad, con tanta fuerza,  con tal derroche, que no solo para un traductor ajeno (aunque tan cercano) resulta  en muchos casos arduo cuando no imposible intentar su versión, sino que en la  misma edición de su poesía completa: <em>De Paulicéia desvairada a Café</em> (Circulo do Livro, São Paulo, s/f) se vio obligado a aclarar el editor en una  nota inicial, nada menos que esto que sigue: &ldquo;Con todo, el propio hecho de que  él apreciaba su manera de registrar el <em>habla brasileña</em> y hacía de eso  una característica notable de su estilo impone reservas al intento de  actualización&rdquo;. Impulso al parecer irrefrenable ya que, no obstante lo  antedicho, llevó a ese mismo editor a efectuar allí &ldquo;alguna actualización en la  ortografía&rdquo; de un escritor que se había propuesto, pero no pudo concretar, nada  menos que una <em>Gramatiquinha da Fala Brasileira.</em></p>
<p>Lo que nos obliga a aclarar que de ningún modo esa  asunción de la propia identidad se realizó para los modernistas brasileños de  una manera superficialmente descriptiva o apenas paisajística, ni mucho menos  que la radical comprensión y aprehensión del habla legítimamente popular se  redujo para ellos a la tibia incorporación de algunos modismos para salpicar  aquí y allá apenas un poco de color local. Como artistas hondamente auténticos  que eran, la experiencia cabal de su identidad se dio naturalmente,  directamente con el fluir de su obra, y su lenguaje no solo está lejos de  emular lo aparente sino que por el contrario comprende, implica precisamente  los mismos mecanismos constitutivos (fonéticos, semánticos y hasta ideológicos)  del habla común, pero haciéndolos texto, escritura, poema, con entera, con  insoslayable y hasta desafiante libertad.</p>
<p>Esa libertad que para Mário de Andrade llegó, justamente,  a constituirse en una actitud incluso tan saludablemente desmedida de  inventiva, que resulta nítidamente todo lo contrario de cualquier seguidismo  más o menos servil. No es la apariencia, la mera cáscara del habla nacional lo  que aspira a mimetizar, a adoptar a priori, por preconcepto o por razonamiento,  sino que lo que se procura es simplemente, maravillosamente, nada menos que  permitir que fluya con libertad el espíritu, el meollo actuante de esa habla,  lo que hay de naturalmente vivo y original en su estructura y en su  funcionamiento, y que está tan activo en uno, en el poeta en este caso, como en  todos los otros que lo hablan junto con él. Eso que permitió a la poesía de  Mário de Andrade (como lo hizo de manera suprema esa cumbre que es la narrativa,  la poesía encarnada de João Guimaraes Rosa), volverse un organismo vivo de  lenguaje, un ser autónomo, que para respirar como cuerpo ha debido generar sus  propias estructuras, al igual que lo hace la vida misma, la mismísima vida, y  como hace también la lengua viva de la calle cuando es un pueblo fecunda y  espontáneamente creador quien la mantiene en combustión, en uso.</p>
<p>Permítaseme entonces, a mí, en nombre del respeto y la  admiración por su persona y por su obra, este chueco intento de aproximación a  su poesía, ferviente y bella, basado únicamente en la profunda convicción de  que, salvadas las inevitables distancias que muy especialmente en este caso  median con el original, podrá también su lirismo desmitificador resultar muy  beneficioso entre nosotros, para nosotros.</p>
